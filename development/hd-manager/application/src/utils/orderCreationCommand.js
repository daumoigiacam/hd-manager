import {buildBusinessDocumentId,ensureBusinessMutationId} from './businessMutationIds.js';

const own=(value,key)=>Object.hasOwn(value||{},key);
const conflict=()=>Object.assign(new Error('Mã tạo đơn đã được dùng với dữ liệu khác. Vui lòng kiểm tra đơn đã lưu trước khi tạo đơn mới.'),{code:'firestore/order-command-conflict'});
const canonical=value=>Array.isArray(value)?value.map(canonical):value&&typeof value==='object'
  ?Object.fromEntries(Object.keys(value).sort().map(key=>[key,canonical(value[key])])):value;
export function orderCreationIntent({companyId,employeeId,orderData,financialData}){
  const id=ensureBusinessMutationId(orderData.clientMutationId,'order');
  const clean={...orderData,clientMutationId:id};
  // Runtime timestamps are generated by the transaction caller, never part of
  // an immutable form intent. Replaying an old command cannot edit its invoice.
  delete clean.createdAt;delete clean.updatedAt;delete clean.orderCreationCommand;
  const fingerprint=JSON.stringify(canonical(JSON.parse(JSON.stringify([companyId,employeeId,clean,financialData]))));
  return {id:buildBusinessDocumentId('o',companyId,id),command:{id,fingerprint}};
}
export const isOrderCreationCommand=value=>value!==null&&typeof value==='object'&&[Object.prototype,null].includes(Object.getPrototypeOf(value))
  &&Reflect.ownKeys(value).length===2&&['id','fingerprint'].every(key=>own(value,key)&&Object.hasOwn(Object.getOwnPropertyDescriptor(value,key),'value'))
  &&typeof value.id==='string'&&/^[A-Za-z0-9][A-Za-z0-9_-]{0,159}$/.test(value.id)
  &&typeof value.fingerprint==='string'&&value.fingerprint.length>0;
export const orderCreationCommandMatches=(value,command)=>isOrderCreationCommand(value)&&isOrderCreationCommand(command)
  &&value.id===command.id&&value.fingerprint===command.fingerprint;

export function assertOrderCreationReplay(data,command,companyId){
  if(data?.companyId!==companyId||data.clientMutationId!==command.id||!orderCreationCommandMatches(data.orderCreationCommand,command))throw conflict();
  return data;
}
export function validateOrderCreationWrites(writes,companyId){
  const command=writes[0]?.orderCreationCommand;
  const orders=writes.filter(row=>row.collectionName==='orders');
  if(!isOrderCreationCommand(command)||orders.length!==1||writes.length>3||writes.some(row=>!orderCreationCommandMatches(row.orderCreationCommand,command)
    ||row.payload.companyId!==companyId||own(row,'assetCommand')||own(row,'deliveryCommand')||own(row,'ifAbsent')||own(row,'resolveOnce')))throw conflict();
  const order=orders[0],id=order.documentId;
  assertOrderCreationReplay(order.payload,command,companyId);
  if(id!==buildBusinessDocumentId('o',companyId,command.id))throw conflict();
  for(const row of writes){
    if(row===order)continue;
    const payment=row.collectionName==='payments'&&row.documentId===`p_order_upfront_${id}`&&row.payload.orderId===id&&row.payload.customerId===order.payload.customerId;
    const expense=row.collectionName==='expenses'&&row.documentId===`exp_order_${id}`;
    if(!(payment||expense)||row.payload.sourceOrderId!==id||!Number.isFinite(row.payload.amount)||row.payload.amount<=0)throw conflict();
  }
  return {order,command};
}

export function commitOrderCreationWrites({writes,companyId,transaction,reference}){
  const {order,command}=validateOrderCreationWrites(writes,companyId);
  return transaction(async tx=>{
    const snapshots=await Promise.all(writes.map(row=>tx.get(reference(row))));
    if(snapshots.some(row=>row.exists()&&row.data().companyId!==companyId))throw conflict();
    const index=writes.indexOf(order),existing=snapshots[index];
    if(existing.exists()){
      assertOrderCreationReplay(existing.data(),command,companyId);
      return {existingDocuments:writes.flatMap((row,i)=>snapshots[i].exists()?[{...row,payload:snapshots[i].data()}]:[])};
    }
    if(snapshots.some(row=>row.exists()))throw conflict();
    for(const row of writes)tx.set(reference(row),row.payload,row.options||{});
    return {existingDocuments:[]};
  });
}
